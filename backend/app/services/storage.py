"""Storage for original uploaded files.

Files are addressed by a storage key generated by the server ("<owner_id>/<document_id>.<ext>"),
never by the user's filename, so a crafted filename cannot reach another path. Development uses
a local folder; production uses S3-compatible object storage (Neon Object Storage), because a
hosted server's disk is wiped on every deploy.
"""

from pathlib import Path
from typing import Protocol

import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError

from app.core.errors import NotFoundError, StorageError


class FileStorage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...

    def read(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...


class LocalFileStorage:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()
        self._root.mkdir(parents=True, exist_ok=True)

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def read(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise NotFoundError("The original file is no longer available.") from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def _path(self, key: str) -> Path:
        path = (self._root / key).resolve()
        if not path.is_relative_to(self._root):
            raise ValueError(f"storage key escapes the storage root: {key!r}")
        return path


class S3FileStorage:
    """Any S3-compatible service. Neon Object Storage requires path-style addressing and SigV4."""

    def __init__(self, *, bucket: str, endpoint_url: str, access_key_id: str, secret_access_key: str, region: str) -> None:
        self._bucket = bucket
        self._client = boto3.client(
            "s3",
            endpoint_url=endpoint_url,
            aws_access_key_id=access_key_id,
            aws_secret_access_key=secret_access_key,
            region_name=region,
            config=Config(
                signature_version="s3v4",
                s3={"addressing_style": "path"},
                connect_timeout=10,
                read_timeout=30,
                retries={"max_attempts": 3, "mode": "standard"},
            ),
        )

    def save(self, key: str, data: bytes) -> None:
        try:
            self._client.put_object(Bucket=self._bucket, Key=key, Body=data)
        except (BotoCoreError, ClientError) as exc:
            raise StorageError() from exc

    def read(self, key: str) -> bytes:
        try:
            return self._client.get_object(Bucket=self._bucket, Key=key)["Body"].read()
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in ("NoSuchKey", "404"):
                raise NotFoundError("The original file is no longer available.") from exc
            raise StorageError() from exc
        except BotoCoreError as exc:
            raise StorageError() from exc

    def delete(self, key: str) -> None:
        try:
            self._client.delete_object(Bucket=self._bucket, Key=key)  # succeeds if already gone
        except (BotoCoreError, ClientError) as exc:
            raise StorageError() from exc
